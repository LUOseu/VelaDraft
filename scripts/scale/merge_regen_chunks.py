#!/usr/bin/env python
"""Merge chunked regen outputs back into the shared run dir (order preserving).

Each chunk was regenerated by ``scripts/generate_target_data.py`` in its own run
dir over a contiguous row slice (``scripts/scale/split_input_rows.py``). This
script rewrites the shared stage so the trainer's stage-digest gate accepts it:

* ``regen/target_data.jsonl``  -- chunk rows concatenated in chunk order;
* ``regen/skipped.jsonl``      -- same order;
* ``regen/regen_stats.json``   -- chunk A's schema, numbers recomputed from the
  merged rows (``num_input`` = the full input slice, so the keep rate is the
  real one);
* ``regen/stage_manifest.json``-- the inputs digest a full ``--limit None`` run
  would have written (the chunk runs recorded ``limit=<chunk>``);
* ``provenance.json``          -- the merge recorded as the regen stage.

Usage:
  merge_regen_chunks.py --shared-dir SHARED --config CFG --chunk DIR [--chunk DIR ...]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from vlm_dflash.cli import stage_digest, stage_digest_payload, write_stage_manifest
from vlm_dflash.contract import ensure_contract
from vlm_dflash.provenance import identity_from_contract, record_stage
from vlm_dflash.target.regen import _length_summary
from vlm_dflash.utils import read_json, write_json, write_jsonl


def read_jsonl(path: Path) -> list[dict]:
    with path.open() as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--shared-dir", required=True)
    parser.add_argument("--config", required=True)
    parser.add_argument("--chunk", action="append", required=True, help="chunk run dir, in row order")
    args = parser.parse_args()

    import yaml

    shared = Path(args.shared_dir)
    cfg = yaml.safe_load(Path(args.config).read_text())
    contract = ensure_contract(cfg, shared)

    rows: list[dict] = []
    skipped: list[dict] = []
    chunk_stats: list[dict] = []
    per_chunk: list[dict] = []
    for chunk in args.chunk:
        chunk_dir = Path(chunk)
        chunk_rows = read_jsonl(chunk_dir / "regen" / "target_data.jsonl")
        chunk_skipped_path = chunk_dir / "regen" / "skipped.jsonl"
        chunk_skipped = read_jsonl(chunk_skipped_path) if chunk_skipped_path.exists() else []
        stats = read_json(chunk_dir / "regen" / "regen_stats.json")
        rows.extend(chunk_rows)
        skipped.extend(chunk_skipped)
        chunk_stats.append(stats)
        per_chunk.append(
            {
                "dir": str(chunk_dir),
                "num_input": int(stats["num_input"]),
                "num_kept": int(stats["num_kept"]),
                "num_skipped": int(stats["num_skipped"]),
            }
        )

    stats = dict(chunk_stats[0])
    max_new_tokens = int(stats.get("max_new_tokens") or 0) or None
    num_input = sum(entry["num_input"] for entry in per_chunk)
    skip_reasons: dict[str, int] = {}
    for entry in chunk_stats:
        for reason, count in (entry.get("skip_reasons") or {}).items():
            skip_reasons[reason] = skip_reasons.get(reason, 0) + int(count)
    stats.update(
        {
            "num_input": num_input,
            "num_kept": len(rows),
            "num_skipped": num_input - len(rows),
            "skip_reasons": skip_reasons,
            "answer_token_histogram": _length_summary(
                [len(row["regen"]["answer_ids"]) for row in rows], cap=max_new_tokens
            ),
            "prompt_token_histogram": _length_summary(
                [len(row["regen"]["prompt_ids"]) for row in rows], cap=None
            ),
            "chunked": {
                "note": "regenerated as contiguous row chunks in separate processes; rows concatenated in order",
                "chunks": per_chunk,
            },
        }
    )

    regen_dir = shared / "regen"
    write_jsonl(regen_dir / "target_data.jsonl", rows)
    write_jsonl(regen_dir / "skipped.jsonl", skipped)
    write_json(regen_dir / "regen_stats.json", stats)

    data_digest = stage_digest(cfg, contract, "data", None, limit=None)
    regen_digest = stage_digest(cfg, contract, "regen", data_digest, limit=None)
    write_stage_manifest(
        shared, "regen", stage_digest_payload(cfg, contract, "regen", data_digest, limit=None), regen_digest
    )
    record_stage(
        shared,
        "regen",
        {
            "identity": identity_from_contract(contract),
            "stats": stats,
            "code": "vlm_dflash.target.regen.run_regen (chunked merge)",
        },
    )
    print(
        f"merge_regen_chunks: kept={len(rows)}/{num_input} "
        f"({len(rows) / max(1, num_input) * 100:.1f}%) skipped={len(skipped)} reasons={skip_reasons} "
        f"regen_digest={regen_digest[:12]}"
    )


if __name__ == "__main__":
    main()
